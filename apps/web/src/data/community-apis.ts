export type AIPParameter = {
  type: "string" | "number" | "boolean" | "ISO8601" | "enum";
  description: string;
  required: boolean;
  enum?: string[];
  default?: unknown;
  example?: unknown;
};

export type AIPIntent = {
  id: string;
  name: string;
  description: string;
  triggers: string[];
  category: string;
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  endpoint: string;
  parameters?: Record<string, AIPParameter>;
  requires_auth: boolean;
  destructive: boolean;
  confirmation_required: boolean;
};

